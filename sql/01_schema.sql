CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(12) NOT NULL,
    FULL_NAME VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(160 CHAR) NOT NULL,
    REGION VARCHAR2(12 CHAR) NOT NULL,
    CREATED_AT DATE NOT NULL,
    CONSTRAINT CUSTOMERS_PK PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT CUSTOMERS_ID_CK CHECK (CUSTOMER_ID > 0),
    CONSTRAINT CUSTOMERS_REGION_CK CHECK (REGION IN ('NORTH','SOUTH','EAST','WEST','CENTRAL'))
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER(12) NOT NULL,
    CATEGORY VARCHAR2(20 CHAR) NOT NULL,
    PRODUCT_NAME VARCHAR2(100 CHAR) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    IS_ACTIVE NUMBER(1) NOT NULL,
    CONSTRAINT PRODUCTS_PK PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT PRODUCTS_ID_CK CHECK (PRODUCT_ID > 0),
    CONSTRAINT PRODUCTS_PRICE_CK CHECK (UNIT_PRICE > 0),
    CONSTRAINT PRODUCTS_ACTIVE_CK CHECK (IS_ACTIVE IN (0,1))
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER(12) NOT NULL,
    CUSTOMER_ID NUMBER(12) NOT NULL,
    ORDER_DATE DATE NOT NULL,
    STATUS VARCHAR2(12 CHAR) NOT NULL,
    TOTAL_AMOUNT NUMBER(16,2) NOT NULL,
    CONSTRAINT ORDERS_PK PRIMARY KEY (ORDER_ID),
    CONSTRAINT ORDERS_ID_CK CHECK (ORDER_ID > 0),
    CONSTRAINT ORDERS_TOTAL_CK CHECK (TOTAL_AMOUNT > 0),
    CONSTRAINT ORDERS_STATUS_CK CHECK (STATUS IN ('NEW','PAID','SHIPPED','CANCELLED')),
    CONSTRAINT ORDERS_CUSTOMER_FK FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID)
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER(12) NOT NULL,
    ORDER_ID NUMBER(12) NOT NULL,
    PRODUCT_ID NUMBER(12) NOT NULL,
    QUANTITY NUMBER(5) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    CONSTRAINT ORDER_ITEMS_PK PRIMARY KEY (ORDER_ITEM_ID),
    CONSTRAINT ITEMS_ID_CK CHECK (ORDER_ITEM_ID > 0),
    CONSTRAINT ITEMS_QTY_CK CHECK (QUANTITY > 0),
    CONSTRAINT ITEMS_PRICE_CK CHECK (UNIT_PRICE > 0),
    CONSTRAINT ITEMS_ORDER_FK FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
    CONSTRAINT ITEMS_PRODUCT_FK FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
);

CREATE TABLE OSPA_DATASET (
    DATASET_ID NUMBER(1) NOT NULL,
    PROFILE VARCHAR2(10 CHAR) NOT NULL,
    SEED NUMBER(19) NOT NULL,
    MANIFEST VARCHAR2(4000 CHAR) NOT NULL,
    LOADED_AT DATE NOT NULL,
    CONSTRAINT OSPA_DATASET_PK PRIMARY KEY (DATASET_ID),
    CONSTRAINT DATASET_SINGLE_CK CHECK (DATASET_ID = 1),
    CONSTRAINT DATASET_SEED_CK CHECK (SEED >= 0),
    CONSTRAINT DATASET_PROFILE_CK CHECK (PROFILE IN ('tiny','small','medium','large'))
);
